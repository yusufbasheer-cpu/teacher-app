import { randomUUID } from "node:crypto";
import type { StructuredLessonSlideModel } from "@/lib/ppt-structured-lesson";
import type { PresentationLanguage } from "@/lib/ppt-language";
import { acquireGammaRun, dedupeKey, recordCredits } from "./budget";
import { downloadGammaExport, runGammaGeneration, type GammaDeps } from "./client";
import { getGammaConfig, GammaError, type GammaConfig } from "./config";
import { buildGammaPayload } from "./payload";
import { compareToSnapshot, extractPptx, type ValidationReport } from "./validate";

export type GammaRunMetrics = {
  presentationId: string;
  provider: "gamma";
  generationId?: string;
  requestedSlides: number;
  actualSlides?: number;
  imageModel: string;
  imageSource: string;
  imagesPictureCount?: number;
  imageMediaFiles?: number;
  creditsDeducted?: number;
  creditsRemaining?: number;
  durationMs: number;
  outcome: "success" | "failure";
  failureCode?: string;
  retryCount: number;
  pollCount: number;
  validation?: "passed" | "failed";
  neutralisedBreaks: number;
  overRunBudget?: boolean;
};

export type GammaRenderResult = { buffer: Buffer; validation: ValidationReport; metrics: GammaRunMetrics };

/**
 * Teacher content (already generated by the existing DeepSeek pipeline) → Gamma → validated PPTX.
 * Never throws away a downloaded file because validation failed: the caller gets the report and decides.
 * Logs metrics only (no slide text, no API key, no export URL).
 */
export async function renderPptxWithGamma(
  params: {
    deck: StructuredLessonSlideModel[];
    title: string;
    language: PresentationLanguage;
    userId: string;
    config?: GammaConfig;
  },
  deps: GammaDeps = {},
): Promise<GammaRenderResult> {
  const config = params.config ?? getGammaConfig();
  const t0 = Date.now();
  const metrics: GammaRunMetrics = {
    presentationId: randomUUID(),
    provider: "gamma",
    requestedSlides: params.deck.length,
    imageModel: config.imageModel ?? "gamma-auto",
    imageSource: config.imageSource,
    durationMs: 0,
    outcome: "failure",
    retryCount: 0,
    pollCount: 0,
    neutralisedBreaks: 0,
  };
  const { request, snapshot, neutralisedBreaks } = buildGammaPayload({
    deck: params.deck,
    title: params.title,
    language: params.language,
    config,
  });
  metrics.neutralisedBreaks = neutralisedBreaks;

  const release = acquireGammaRun(dedupeKey(params.userId, String(request.inputText)), params.deck.length, config);
  try {
    const gen = await runGammaGeneration(config, request, deps);
    metrics.generationId = gen.generationId;
    metrics.retryCount = gen.retryCount;
    metrics.pollCount = gen.pollCount;
    metrics.creditsDeducted = gen.credits.deducted;
    metrics.creditsRemaining = gen.credits.remaining;
    recordCredits(gen.credits.deducted);
    metrics.overRunBudget = (gen.credits.deducted ?? 0) > config.maxCreditsPerRun;

    const buffer = await downloadGammaExport(config, gen.exportUrl, deps);
    const validation = compareToSnapshot(snapshot, await extractPptx(buffer));
    metrics.actualSlides = validation.actualSlides;
    metrics.imagesPictureCount = validation.pictures;
    metrics.imageMediaFiles = validation.mediaFiles;
    metrics.validation = validation.passed ? "passed" : "failed";
    metrics.outcome = "success";
    return { buffer, validation, metrics };
  } catch (e) {
    if (e instanceof GammaError) {
      metrics.failureCode = e.code;
      metrics.generationId ??= e.extra.generationId;
    } else {
      metrics.failureCode = "unexpected";
    }
    throw e;
  } finally {
    release();
    metrics.durationMs = Date.now() - t0;
    console.log(`[gamma-ppt] ${JSON.stringify(metrics)}`);
  }
}
