import { createHash } from "node:crypto";
import type { StructuredLessonSlideModel } from "@/lib/ppt-structured-lesson";
import type { PresentationLanguage } from "@/lib/ppt-language";
import { createGeneration, downloadGammaExport, getGeneration, pollGeneration, type GammaDeps, type GammaStatusResult } from "./client";
import { getGammaConfig, GammaError, type GammaConfig } from "./config";
import { buildGammaPayload, type GammaLessonMeta } from "./payload";
import { checkAdmission } from "./policy";
import { getDefaultGammaStore, type GammaRow, type GammaStore } from "./store";
import { checkLayout, compareToSnapshot, extractPptx, type ValidationReport } from "./validate";
import { insertSpeakerNotes, readSpeakerNotes } from "./notes";
import { scanStudentFacingText, validateSelectedSdg } from "@/lib/ppt-educational-quality";
import { artifactPath, readGammaArtifact, storeGammaArtifact } from "./artifact";
import { buildRequiredVisualIntents, verifyRequiredVisualCoverage } from "@/lib/ppt-visual-intent";

export type GammaRunMetrics = {
  presentationId?: string;
  provider: "gamma";
  generationId?: string;
  requestedSlides: number;
  actualSlides?: number;
  imageModel: string;
  imageSource: string;
  imagesPictureCount?: number;
  imageMediaFiles?: number;
  creditsDeducted?: number;
  creditsRemaining?: number;
  durationMs: number;
  outcome: "success" | "failure";
  failureCode?: string;
  retryCount: number;
  pollCount: number;
  resumed: boolean;
  validation?: ValidationReport["verdict"];
  requiredVisualValidation?: "passed" | "uncertain" | "failed";
  neutralisedBreaks: number;
  overRunBudget?: boolean;
};

export type GammaRenderResult = { buffer: Buffer; validation: ValidationReport; metrics: GammaRunMetrics };

type Completed = Extract<GammaStatusResult, { state: "completed" }>;

/**
 * Teacher content (already generated by the existing DeepSeek pipeline) → Gamma → validated PPTX.
 *
 * Billing safety (Gamma documents no idempotency key and no lookup other than by generation id):
 *  - A ledger row is written BEFORE the paid create call; a unique index allows one active generation per user.
 *  - The generation id is persisted the moment Gamma returns it. Polling timeouts / aborted downloads never
 *    release the row: the next identical request RESUMES (status lookup + download) with no new submission.
 *  - If the create call's outcome is unknown (timeout, network error, 5xx, no id), the row is marked `unknown`
 *    and the user cannot submit again until the quarantine passes; the row's credits stay reserved afterwards.
 *  - Credits are written to the ledger whenever a completed status is observed, including on resumption.
 * Logs metrics only (no slide text, API key or export URL).
 */
export async function renderPptxWithGamma(
  params: {
    deck: StructuredLessonSlideModel[];
    title: string;
    language: PresentationLanguage;
    userId: string;
    /** Topic/subject/grade for the cover. Must match what the artifact lookup sends, or reuse never hits. */
    lesson?: GammaLessonMeta;
    /** Which lesson sections carry a platform picture in this request; it changes the platform pagination. */
    hasImage?: (deckIdx: number) => boolean;
    config?: GammaConfig;
    store?: GammaStore;
    /** When the HTTP request began; the overall budget is measured from here. */
    startedAt?: number;
  },
  deps: GammaDeps = {},
): Promise<GammaRenderResult> {
  const now = deps.now ?? Date.now;
  const t0 = params.startedAt ?? now();
  const config = params.config ?? getGammaConfig();
  const store = params.store ?? getDefaultGammaStore();
  const deadline = t0 + config.overallBudgetMs;
  const metrics: GammaRunMetrics = {
    provider: "gamma",
    requestedSlides: 0, // set from the canonical (paginated) deck below
    imageModel: config.imageModel ?? "gamma-auto",
    imageSource: config.imageSource,
    durationMs: 0,
    outcome: "failure",
    retryCount: 0,
    pollCount: 0,
    resumed: false,
    neutralisedBreaks: 0,
  };
  const { request, snapshot, neutralisedBreaks, layout, slides, notes } = buildGammaPayload({ deck: params.deck, title: params.title, language: params.language, config, lesson: params.lesson, hasImage: params.hasImage });
  const visualIntents = buildRequiredVisualIntents({
    deck: params.deck,
    topic: params.lesson?.topic ?? params.title,
    subject: params.lesson?.subject ?? "Lesson",
    grade: params.lesson?.grade ?? "",
  }).map((intent) => ({ ...intent, imageSource: "gamma" as const, assetStatus: "provider-generated-unverified" as const }));
  // Content (strict, line by line) and layout (image dominance) are separate checks; only content decides the verdict.
  const selectedSdg = params.deck.find((m) => m.educationalMetadata?.selectedSdg)?.educationalMetadata?.selectedSdg;
  const validateDeck = (deck: Awaited<ReturnType<typeof extractPptx>>): ValidationReport => {
    const content = compareToSnapshot(snapshot, deck);
    // Final-PPTX student text check: the canonical slides are already clean, so a compliance claim, an ability label
    // or a different SDG in Gamma's export means Gamma introduced it. That is a content failure, not a layout note.
    const exported = deck.slides.map((s, i) => ({ slideTitle: `Slide ${i + 1}`, body: s.paragraphs.map((p) => p.text).join("\n") }));
    const studentText = scanStudentFacingText(exported).map((f) => `slide ${f.slide}: ${f.label} ("${f.match.slice(0, 60)}")`);
    const sdg = selectedSdg ? validateSelectedSdg(exported, selectedSdg) : [];
    const reasons = [...content.reasons, ...studentText, ...sdg];
    const verdict = reasons.length ? "failed" : content.verdict;
    return {
      ...content,
      verdict,
      passed: verdict === "passed",
      reasons,
      layout: checkLayout(layout, deck),
      requiredVisuals: verifyRequiredVisualCoverage({ intents: visualIntents, physicalSlides: slides, actualSlides: deck.slides }),
    };
  };
  /**
   * Writes Layah's per-slide speaker notes into Gamma's export, then proves nothing else moved: the strict content
   * comparison runs again on the modified file and every slide must read back non-empty notes. On any doubt the
   * original file is kept and the report says the notes are missing.
   */
  const withSpeakerNotes = async (buffer: Buffer): Promise<{ buffer: Buffer; validation: ValidationReport }> => {
    const before = validateDeck(await extractPptx(buffer));
    try {
      const updated = await insertSpeakerNotes(buffer, notes);
      const after = validateDeck(await extractPptx(updated));
      const written = await readSpeakerNotes(updated);
      const slidesWithNotes = written.filter((n) => n.trim()).length;
      if (after.verdict !== before.verdict || after.reasons.join("|") !== before.reasons.join("|")) throw new Error("content changed while adding notes");
      if (slidesWithNotes !== written.length) throw new Error(`${written.length - slidesWithNotes} slide(s) still have no notes`);
      return { buffer: updated, validation: { ...after, speakerNotes: { added: true, slidesWithNotes, totalSlides: written.length } } };
    } catch (e) {
      const reason = e instanceof Error ? e.message : String(e);
      console.warn(`[gamma-ppt] speaker notes not added: ${reason}`);
      return {
        buffer,
        validation: {
          ...before,
          verdict: before.verdict === "passed" ? "uncertain" : before.verdict,
          passed: false,
          uncertainties: [...before.uncertainties, `speaker notes could not be added (${reason})`],
          speakerNotes: { added: false, slidesWithNotes: 0, totalSlides: before.actualSlides, reason },
        },
      };
    }
  };
  metrics.neutralisedBreaks = neutralisedBreaks;
  metrics.requestedSlides = snapshot.length;
  const requestHash = createHash("sha256").update(JSON.stringify(request)).digest("hex");
  const patch = (row: GammaRow, p: Parameters<GammaStore["update"]>[1]) => store.update(row.id, p, now());

  try {
    let row: GammaRow | null = null;
    let completed: Completed | null = null;
    const imageOptions = request.imageOptions as { source?: string; style?: string } | undefined;
    const reusable = store.findReusableArtifact ? await store.findReusableArtifact({ userId: params.userId, requestHash, themeId: typeof request.themeId === "string" ? request.themeId : null, imageSource: imageOptions?.source ?? null, imageStyle: imageOptions?.style ?? null }) : null;
    if (reusable?.artifactPath) {
      const stored = process.env.VITEST ? Buffer.alloc(0) : await readGammaArtifact(reusable.artifactPath);
      if (!process.env.VITEST) {
        const { buffer, validation } = await withSpeakerNotes(stored);
        metrics.presentationId = reusable.id;
        metrics.generationId = reusable.generationId ?? undefined;
        metrics.resumed = true;
        metrics.actualSlides = validation.actualSlides;
        metrics.imagesPictureCount = validation.pictures;
        metrics.imageMediaFiles = validation.mediaFiles;
        metrics.validation = validation.verdict;
        metrics.requiredVisualValidation = validation.requiredVisuals?.verdict;
        metrics.creditsDeducted = reusable.creditsDeducted ?? undefined;
        metrics.outcome = validation.verdict === "failed" ? "failure" : "success";
        return { buffer, validation, metrics };
      }
    }


    // ── 1. Settle anything already in the ledger for this user (never submit blindly) ──
    const active = await store.findActiveForUser(params.userId);
    if (active) {
      if (!active.generationId) {
        const waitMs = active.createdAt + config.unknownQuarantineMs - now();
        if (waitMs > 0) {
          throw new GammaError(
            "submission_unknown",
            `An earlier Gamma submission has an unknown outcome (it may still be generating and billing). New submissions are blocked for about ${Math.ceil(waitMs / 60_000)} more minute(s).`,
          );
        }
        await patch(active, { status: "abandoned", errorCode: "submission_unknown" }); // credits stay reserved by policy
      } else {
        const st = await getGeneration(config, active.generationId, deps, deadline);
        if (st.state === "completed") {
          await patch(active, { status: "completed", creditsDeducted: st.credits.deducted ?? null, creditsRemaining: st.credits.remaining ?? null });
          if (active.requestHash === requestHash) {
            row = { ...active, status: "completed" };
            completed = st;
          }
        } else if (st.state === "failed") {
          await patch(active, { status: "failed", errorCode: "generation_failed", creditsDeducted: st.credits.deducted ?? null });
        } else if (now() - active.createdAt > config.staleActiveMs) {
          await patch(active, { status: "abandoned", errorCode: "stale" });
        } else if (active.requestHash === requestHash) {
          row = active; // still running: resume polling below, no new submission
        } else {
          throw new GammaError("generation_in_progress", "Another Gamma generation for this account is still running. Wait for it to finish before starting a different one.");
        }
        if (row) metrics.resumed = true;
      }
    }
    if (!row) {
      const undelivered = await store.findUndelivered(params.userId, requestHash, now() - config.undeliveredWindowMs);
      if (undelivered?.generationId) {
        const st = await getGeneration(config, undelivered.generationId, deps, deadline);
        if (st.state === "completed") {
          row = undelivered;
          completed = st;
          metrics.resumed = true;
        }
      }
    }

    // ── 2. New paid submission (only when nothing could be resumed) ──
    if (!row) {
      await checkAdmission(store, config, params.userId, snapshot.length, now());
      const inserted = await store.insertSubmitting({ userId: params.userId, requestHash, requestedSlides: snapshot.length, sourceSnapshot: snapshot, now: now() });
      if (!inserted) throw new GammaError("duplicate_in_flight", "A Gamma generation is already running for this account.");
      row = inserted;
      let created: Awaited<ReturnType<typeof createGeneration>>;
      try {
        created = await createGeneration(config, request, deps, deadline);
      } catch (e) {
        const code = e instanceof GammaError ? e.code : "unexpected";
        // Unknown outcome keeps the user locked out of a re-submit; definite failures free the lock.
        await patch(inserted, { status: code === "submission_unknown" ? "unknown" : "failed", errorCode: code });
        throw e;
      }
      // From here a paid generation EXISTS: the row must never be marked failed (that would free the lock for a duplicate).
      metrics.retryCount = created.retryCount;
      metrics.generationId = created.generationId;
      row = { ...row, generationId: created.generationId, status: "pending" };
      try {
        await patch(row, { status: "pending", generationId: created.generationId });
      } catch (e) {
        // Ledger write lost: the row stays 'submitting' (= unknown outcome, user stays blocked). Log the id (not a secret)
        // so an operator can reconcile it by hand.
        console.error(`[gamma-ppt] LEDGER WRITE FAILED after paid submission ${JSON.stringify({ rowId: inserted.id, generationId: created.generationId })}`);
        throw e;
      }
    }
    metrics.generationId = row.generationId ?? undefined;
    metrics.presentationId = row.id;

    // ── 3. Wait for completion (resumes an existing id; a timeout here leaves the row pending) ──
    if (!completed) {
      const polled = await pollGeneration(config, row.generationId as string, deps, deadline);
      metrics.pollCount = polled.pollCount;
      if (polled.result.state === "failed") {
        await patch(row, { status: "failed", errorCode: "generation_failed", creditsDeducted: polled.result.credits.deducted ?? null, creditsRemaining: polled.result.credits.remaining ?? null });
        metrics.creditsDeducted = polled.result.credits.deducted;
        if (polled.result.statusCode === 402 || /credit/i.test(polled.result.message)) {
          throw new GammaError("insufficient_credits", "Gamma generation failed: insufficient credits.", { generationId: row.generationId ?? undefined });
        }
        throw new GammaError("generation_failed", `Gamma generation failed: ${polled.result.message}`, { generationId: row.generationId ?? undefined });
      }
      completed = polled.result;
      await patch(row, { status: "completed", creditsDeducted: completed.credits.deducted ?? null, creditsRemaining: completed.credits.remaining ?? null });
    }
    metrics.creditsDeducted = completed.credits.deducted;
    metrics.creditsRemaining = completed.credits.remaining;
    metrics.overRunBudget = (completed.credits.deducted ?? 0) > config.maxCreditsPerRun;
    if (!completed.exportUrl) {
      throw new GammaError("generation_failed", "Gamma completed but returned no PPTX export URL. Retry shortly; the generation is resumable without a new charge.", { generationId: row.generationId ?? undefined });
    }

    // ── 4. Fetch + validate. Any failure here leaves the row completed/undelivered, i.e. resumable for free ──
    const { buffer, validation } = await withSpeakerNotes(await downloadGammaExport(config, completed.exportUrl, deps, deadline));
    // Unit tests intentionally do not bootstrap Supabase Storage; production fails closed if storage is unavailable.
    const artifact = process.env.VITEST ? artifactPath(params.userId, row.generationId as string) : await storeGammaArtifact(params.userId, row.generationId as string, buffer);
    const requestImages = request.imageOptions as { source?: string; style?: string } | undefined;
    await patch(row, {
      artifactPath: artifact,
      validationReport: validation as unknown as Record<string, unknown>,
      requestMetadata: { textMode: request.textMode, cardSplit: request.cardSplit, format: request.format, exportAs: request.exportAs, cardDimensions: (request.cardOptions as { dimensions?: string } | undefined)?.dimensions },
      themeId: typeof request.themeId === "string" ? request.themeId : null,
      imageSource: requestImages?.source ?? null,
      imageStyle: requestImages?.style ?? null,
      durationMs: now() - t0,
      exportMetadata: { actualSlides: validation.actualSlides, pictures: validation.pictures, mediaFiles: validation.mediaFiles },
      delivered: validation.verdict === "passed",
    });
    metrics.actualSlides = validation.actualSlides;
    metrics.imagesPictureCount = validation.pictures;
    metrics.imageMediaFiles = validation.mediaFiles;
    metrics.validation = validation.verdict;
    metrics.requiredVisualValidation = validation.requiredVisuals?.verdict;
    metrics.outcome = validation.verdict === "failed" ? "failure" : "success";
    if (validation.verdict === "failed") {
      metrics.failureCode = "invalid_export";
    }
    return { buffer, validation, metrics };
  } catch (e) {
    if (e instanceof GammaError) {
      metrics.failureCode = e.code;
      metrics.generationId ??= e.extra.generationId;
    } else {
      metrics.failureCode = "unexpected";
    }
    throw e;
  } finally {
    metrics.durationMs = now() - t0;
    console.log(`[gamma-ppt] ${JSON.stringify(metrics)}`);
  }
}
